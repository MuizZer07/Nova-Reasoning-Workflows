def wkappa(a, b, k=3, weights="linear"):
    """Cohen's kappa on credit coded 0..k-1: linear, quadratic, or unweighted ("none")."""
    a, b = np.asarray(a, int), np.asarray(b, int)
    o = np.zeros((k, k))
    np.add.at(o, (a, b), 1)
    o /= o.sum()
    e = np.outer(o.sum(1), o.sum(0))
    d = np.abs(np.subtract.outer(np.arange(k), np.arange(k))) / (k - 1)
    w = {"linear": d, "quadratic": d ** 2, "none": (d > 0).astype(float)}[weights]
    return 1 - (w * o).sum() / (w * e).sum()


def kappa_cat(a, b):
    """Unweighted Cohen's kappa on categorical labels."""
    t = pd.crosstab(pd.Series(list(a), name="a"), pd.Series(list(b), name="b"))
    cats = sorted(set(t.index) | set(t.columns))
    t = t.reindex(index=cats, columns=cats, fill_value=0).to_numpy(float)
    t /= t.sum()
    pe = (t.sum(1) * t.sum(0)).sum()
    return (np.trace(t) - pe) / (1 - pe)


def auc(score, y):
    d = pd.DataFrame({"s": score, "y": y}).dropna()
    pos, neg = d.s[d.y == 1].to_numpy(), d.s[d.y == 0].to_numpy()
    if not len(pos) or not len(neg):
        return np.nan, len(d)
    r = stats.rankdata(np.concatenate([pos, neg]))
    return (r[:len(pos)].sum() - len(pos) * (len(pos) + 1) / 2) / (len(pos) * len(neg)), len(d)


