    # agreement in credit: between the pipelines and, for reference, within each
    def kap(x, y):
        """Linearly weighted Cohen's kappa on credit (0, 0.5, 1)."""
        a_, b_ = (w[x] * 2).round().astype(int).to_numpy(), (w[y] * 2).round().astype(int).to_numpy()
        o = np.zeros((3, 3))
        np.add.at(o, (a_, b_), 1)
        o /= o.sum()
        e_ = np.outer(o.sum(1), o.sum(0))
        wt = np.abs(np.subtract.outer(np.arange(3), np.arange(3))) / 2
        return 1 - (wt * o).sum() / (wt * e_).sum()
